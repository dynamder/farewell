#!/usr/bin/env python3
"""Generate a glyph table: one ink mask per printable ASCII glyph.

Each glyph is rendered into a cell of `--cell` pixels with `--size` points of a
monospace font, then each sub-cell of the `--grid` is marked inked if any pixel
in it carried ink. The result is a fingerprint of "where does this glyph put ink
in a cell", which is what the matcher compares silhouettes against.

The masks are a property of the font, the cell and the grid, not of this script,
so the generated file records all three. `--check` verifies the committed file
against this script and against those arguments; given `--font` it also
re-renders and compares mask by mask.
"""

import argparse
import hashlib
import re
import sys

FIRST, LAST = 0x20, 0x7E
DEFAULT_CELL = (10, 20)
DEFAULT_SIZE = 16
DEFAULT_GRID = (8, 8)

FONT_CANDIDATES = [
    "C:/Windows/Fonts/CascadiaMono.ttf",
    "C:/Windows/Fonts/consola.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf",
    "/System/Library/Fonts/Menlo.ttc",
]


def parse_dims(text):
    m = re.fullmatch(r"(\d+)x(\d+)", text)
    if not m:
        raise argparse.ArgumentTypeError("expected WxH, e.g. 10x20")
    return int(m.group(1)), int(m.group(2))


def script_hash():
    with open(__file__, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()[:16]


def params(cell, size, grid):
    return "grid={}x{};cell={}x{};size={};threshold=any-ink".format(
        grid[0], grid[1], cell[0], cell[1], size
    )


def mask_type(grid):
    return "u{}".format(grid[0] * grid[1])


def find_font(explicit):
    if explicit:
        return explicit
    for path in FONT_CANDIDATES:
        try:
            with open(path, "rb"):
                return path
        except OSError:
            continue
    return None


def rasterise(font_path, cell, size, grid):
    """Return [(codepoint, mask)] for printable ASCII, in codepoint order."""
    from PIL import Image, ImageDraw, ImageFont

    font = ImageFont.truetype(font_path, size)
    cw, ch = cell
    gw, gh = grid
    out = []
    for cp in range(FIRST, LAST + 1):
        im = Image.new("L", (cw, ch), 0)
        ImageDraw.Draw(im).text((0, 0), chr(cp), font=font, fill=255, anchor="la")
        px = im.load()
        mask = 0
        for ry in range(gh):
            for rx in range(gw):
                inked = False
                for y in range(ry * ch // gh, (ry + 1) * ch // gh):
                    for x in range(rx * cw // gw, (rx + 1) * cw // gw):
                        if px[x, y] > 0:
                            inked = True
                            break
                    if inked:
                        break
                mask = (mask << 1) | (1 if inked else 0)
        out.append((cp, mask))
    return out


def dedupe(entries):
    """Drop glyphs whose mask an earlier glyph already has.

    Two glyphs that ink the same sub-cells are indistinguishable to the matcher,
    so the later one could never be chosen; keeping it would only lengthen the
    scan. The dropped codepoints go into the file header so the loss is visible.
    """
    kept, seen, dropped = [], set(), []
    for cp, mask in entries:
        if mask in seen:
            dropped.append(cp)
            continue
        seen.add(mask)
        kept.append((cp, mask))
    return kept, dropped


def render(entries, cell, size, font_path, dropped, grid):
    head = [
        "//! Generated by tools/inkmap.py -- do not edit by hand.",
        "//! script: " + script_hash(),
        "//! params: " + params(cell, size, grid),
        "//! font: " + (font_path.rsplit("/", 1)[-1] if font_path else "unspecified"),
    ]
    if dropped:
        head.append("//! dropped: " + " ".join("0x{:04X}".format(cp) for cp in dropped))
    head += [
        "",
        "/// One printable ASCII codepoint per entry, in codepoint order.",
        "pub const cps = [_]u21{",
    ]
    for cp, _ in entries:
        head.append("    0x{:04X},".format(cp))
    head.append("};")
    head.append("")
    head.append("/// The ink mask for the codepoint at the same index, row-major from")
    head.append("/// the top-left; the most significant bit is the first sub-cell.")
    head.append("pub const masks = [_]{}{{".format(mask_type(grid)))
    width = (grid[0] * grid[1] + 3) // 4
    for _, mask in entries:
        head.append("    0x{:0{}X},".format(mask, width))
    head.append("};")
    return "\n".join(head) + "\n"


def read_committed(path):
    """Pull the header fields and both arrays back out of a generated file."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    fields = dict(re.findall(r"^//! (\w+): (.*)$", text, re.M))
    arrays = []
    for name in ("cps", "masks"):
        m = re.search(name + r" = \[_\]u\d+\{(.*?)\};", text, re.S)
        if not m:
            raise SystemExit("{}: no {} array found".format(path, name))
        arrays.append([int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", m.group(1))])
    return fields, arrays[0], arrays[1]


def describe(entries):
    seen = {}
    for cp, mask in entries:
        seen.setdefault(mask, []).append(cp)
    dupes = [cps for cps in seen.values() if len(cps) > 1]
    ink = sorted(bin(mask).count("1") for _, mask in entries)
    print("glyphs {}  distinct masks {}  ink {}..{}".format(len(entries), len(seen), ink[0], ink[-1]), file=sys.stderr)
    if dupes:
        print("collisions:", file=sys.stderr)
        for cps in dupes:
            print("  " + " ".join("0x{:04X}".format(c) for c in cps), file=sys.stderr)


def dump(entries, wanted, grid):
    gw, gh = grid
    bits = gw * gh
    for cp in wanted:
        mask = dict(entries)[cp]
        print("0x{:04X} ink={}".format(cp, bin(mask).count("1")))
        for r in range(gh):
            print("    " + "".join("#" if (mask >> (bits - 1 - (r * gw + c))) & 1 else "." for c in range(gw)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", help="output file; defaults to src/ink-ascii-GRID.zig")
    ap.add_argument("--font", help="TTF/TTC to measure; defaults to a known monospace")
    ap.add_argument("--cell", type=parse_dims, default=DEFAULT_CELL)
    ap.add_argument("--grid", type=parse_dims, default=DEFAULT_GRID, help="sub-cells per glyph, e.g. 8x16")
    ap.add_argument("--size", type=int, default=DEFAULT_SIZE)
    ap.add_argument("--check", action="store_true", help="verify the committed file, do not write")
    ap.add_argument("--dump", help="print masks for comma separated codepoints, e.g. 0x2e,0x40")
    args = ap.parse_args()

    if args.dump:
        font = find_font(args.font)
        if not font:
            raise SystemExit("no font found; pass --font")
        dump(
            rasterise(font, args.cell, args.size, args.grid),
            [int(v, 0) for v in args.dump.split(",")],
            args.grid,
        )
        return

    if args.out is None:
        args.out = "src/ink-ascii-{}x{}.zig".format(*args.grid)

    fields, cps, masks = ({}, [], [])
    if args.check:
        try:
            fields, cps, masks = read_committed(args.out)
        except OSError as e:
            raise SystemExit("--check: cannot read {}: {}".format(args.out, e))

    if args.check and fields.get("script") != script_hash():
        raise SystemExit(
            "--check: {} was generated by a different inkmap.py ({} here).\n"
            "Regenerate with: zig build inkmap".format(args.out, script_hash())
        )
    if args.check and fields.get("params") != params(args.cell, args.size, args.grid):
        raise SystemExit(
            "--check: {} says [{}], this run says [{}].\n"
            "Regenerate with: zig build inkmap".format(
                args.out, fields.get("params"), params(args.cell, args.size, args.grid)
            )
        )

    # `--check` without --font stays portable: it verifies the recorded script
    # hash and parameters, which are the two things that go stale when someone
    # edits the tool or its arguments and forgets to regenerate. Re-rendering
    # needs the exact font, so it only happens when one is named.
    font = args.font if args.check else find_font(args.font)
    if args.check and not font:
        print("--check: script and params match; pass --font to re-render", file=sys.stderr)
        return
    if not font:
        raise SystemExit("no font found; pass --font")

    entries, dropped = dedupe(rasterise(font, args.cell, args.size, args.grid))
    describe(entries)

    if args.check:
        fresh_cps = [cp for cp, _ in entries]
        fresh_masks = [mask for _, mask in entries]
        if fresh_cps != cps or fresh_masks != masks:
            raise SystemExit("--check: masks differ from {}; regenerate with: zig build inkmap".format(args.out))
        print("--check: {} is up to date".format(args.out), file=sys.stderr)
        return

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(entries, args.cell, args.size, font, dropped, args.grid))
    print("wrote " + args.out, file=sys.stderr)


if __name__ == "__main__":
    main()
